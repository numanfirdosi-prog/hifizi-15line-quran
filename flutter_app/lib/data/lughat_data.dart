class LughatEntry {
  final String word;
  final String urdu;
  final String roman;
  final String root;
  final String linguistic;
  final String sharai;
  final String refBook;
  final String volPage;

  const LughatEntry({
    required this.word,
    required this.urdu,
    required this.roman,
    required this.root,
    required this.linguistic,
    required this.sharai,
    required this.refBook,
    required this.volPage,
  });

  /// Parses a LughatEntry from JSON (used for the online dictionary).
  factory LughatEntry.fromJson(Map<String, dynamic> json) => LughatEntry(
        word: json['word'] as String? ?? '',
        urdu: json['urdu'] as String? ?? '',
        roman: json['roman'] as String? ?? '',
        root: json['root'] as String? ?? '',
        linguistic: json['linguistic'] as String? ?? '',
        sharai: json['sharai'] as String? ?? '',
        refBook: json['refBook'] as String? ?? 'القاموس الجدید',
        volPage: json['volPage'] as String? ?? '',
      );

  /// Serializes to JSON (used for caching the online dictionary).
  Map<String, dynamic> toJson() => {
        'word': word,
        'urdu': urdu,
        'roman': roman,
        'root': root,
        'linguistic': linguistic,
        'sharai': sharai,
        'refBook': refBook,
        'volPage': volPage,
      };
}

